# ------------------------------------------------------------------ formatting

def _pct(x, d=1):
    if not np.isfinite(x):
        return "---"
    s = f"{100 * x:.{d}f}"
    return f"${s}$\\%" if s.startswith("-") else f"{s}\\%"


def _num(x, d=2, sign=False):
    if not np.isfinite(x):
        return "---"
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    return f"${s}$" if s.startswith("-") or sign else s


def _p(x):
    if not np.isfinite(x):
        return "---"
    s = "$<$0.001" if x < 0.001 else f"{x:.3f}"
    return f"\\textbf{{{s}}}" if x < 0.05 else s


def _tabular(spec: str, header: str, rows: list[str], footer: list[str] = ()) -> str:
    out = [f"\\begin{{tabular}}{{{spec}}}", "\\toprule", header + " \\\\", "\\midrule"]
    out += [r + " \\\\" for r in rows]
    if footer:
        out += ["\\midrule"] + [f + " \\\\" for f in footer]
    out += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(out)


