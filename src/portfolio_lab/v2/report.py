def opt_index() -> pd.DatetimeIndex:
    """The common window of the 28 sleeves (1999-01 -> 2026-06)."""
    from portfolio_lab.portfolio import optimizer as opt
    return opt.load_returns().index


def race_table(monthly: pd.DataFrame) -> pd.DataFrame:
    """Exhibit 1 on excess returns: CAGR, vol, maxDD on total returns; Sharpe, its gap to 1/N,
    the LW bootstrap p and the deflated Sharpe on returns in excess of the T-bill."""
    ex = R.excess_returns(monthly)
    srs = {c: float(ex[c].dropna().mean() / ex[c].dropna().std()) for c in ex.columns}
    rows = []
    for name in monthly.columns:
        r = monthly[name].dropna()
        e = ex[name].dropna()
        row = dict(portfolio=name, cagr=float((1 + r).prod() ** (12 / len(r)) - 1),
                   vol=float(r.std() * np.sqrt(12)), sharpe=srs[name] * np.sqrt(12),
                   max_drawdown=D.max_drawdown(r),
                   dsr=I.deflated_sharpe(e, srs.values())["dsr"])
        if name != "1/N":
            t = I.sharpe_diff_test(e, ex["1/N"])
            row.update(d_sharpe=t["delta"] * np.sqrt(12), p_boot=t["p_boot"])
        rows.append(row)
    return pd.DataFrame(rows).sort_values("sharpe", ascending=False).reset_index(drop=True)


def subperiods(runs: dict) -> pd.DataFrame:
    """Per warmup: excess Sharpe on the shared 2009+ months and on the pre-2009 months, and the
    cumulative total return through the GFC (2007-11 -> 2009-02)."""
    rows = []
    for w, m in runs.items():
        ex = R.excess_returns(m)
        for name in m.columns:
            row = dict(warmup=w, portfolio=name)
            for lab, (a, b) in (("2009plus", ("2009-01-01", "2100-01-01")), ("pre2009", PRE_2009)):
                s = ex[name].loc[a:b].dropna()
                row[f"sharpe_{lab}"] = (float(s.mean() / s.std() * np.sqrt(12))
                                        if len(s) > 11 else np.nan)
                row[f"months_{lab}"] = len(s)
            g = m[name].loc[GFC[0]:GFC[1]].dropna()
            row["gfc_return"] = float((1 + g).prod() - 1) if len(g) >= 15 else np.nan
            rows.append(row)
    return pd.DataFrame(rows)


# ------------------------------------------------------------------ LaTeX tables

def tex_race(t: pd.DataFrame) -> str:
    rows = [" & ".join([DISPLAY[r.portfolio], _pct(r.cagr), _pct(r.vol), _num(r.sharpe),
                        f"${100 * r.max_drawdown:.0f}$\\%",
                        _num(getattr(r, "d_sharpe", np.nan), sign=True), _p(getattr(r, "p_boot", np.nan)),
                        _num(r.dsr)])
            for r in t.itertuples()]
    return _tabular("lrrrrrrr", "Contestant & CAGR & Vol & Sharpe & maxDD & $\\Delta$ Sharpe "
                    "& $p$ vs 1/N & DSR", rows)


def tex_riskadj(rt: pd.DataFrame, al: pd.DataFrame) -> str:
    a = al.set_index(["portfolio", "model"])
    rows = []
    for r in rt.itertuples():
        capm, c4 = a.loc[(r.portfolio, "CAPM")], a.loc[(r.portfolio, "Carhart 4F")]
        rows.append(" & ".join([
            DISPLAY[r.portfolio], _num(r.beta), _num(r.sharpe), _num(r.sortino),
            _p(getattr(r, "p_sortino", np.nan)), _pct(r.treynor), _p(getattr(r, "p_treynor", np.nan)),
            _num(100 * capm.alpha_ann, 1, sign=True), _num(capm.t_alpha, 1),
            _num(100 * c4.alpha_ann, 1, sign=True), _num(c4.t_alpha, 1)]))
    head = ("Contestant & $\\beta$ & Sharpe & Sortino & $p$ & Treynor & $p$ & "
            "$\\alpha_{\\text{CAPM}}$ & $t$ & $\\alpha_{\\text{4F}}$ & $t$")
    return _tabular("lrrrrrrrrrr", head, rows)


def tex_alpha_vs_1n(al: pd.DataFrame, order: list[str]) -> str:
    models = list(R.MODELS)
    a = al.set_index(["portfolio", "model"])
    rows = []
    for name in order:
        if name == "1/N":
            continue
        cells = []
        for mdl in models:
            x = a.loc[(name, mdl)]
            pv = x.p_vs_1N
            ps = f"{pv:.2f}" if pv >= 0.01 else (f"{pv:.3f}" if pv >= 0.001 else "$<$0.001")
            s = f"{_num(100 * x.alpha_vs_1N_ann, 1, sign=True)} ({ps})"
            cells.append(f"\\textbf{{{s}}}" if x.p_vs_1N < 0.05 else s)
        rows.append(" & ".join([DISPLAY[name]] + cells))
    head = "Contestant & " + " & ".join(
        {"CAPM": "CAPM", "CAPM (ACWI)": "CAPM (ACWI)", "Carhart 4F": "Carhart 4F",
         "4F + EM market": "4F + EM", "FF5 + WML": "FF5 + WML",
         "FF5 + WML + EM": "FF5 + WML + EM"}[m] for m in models)
    return _tabular("l" + "r" * len(models), head, rows)


def tex_loadings(al: pd.DataFrame, order: list[str]) -> str:
    a = al[al.model == "FF5 + WML"].set_index("portfolio")
    cols = ["dev_mkt_rf", "dev_smb", "dev_hml", "dev_rmw", "dev_cma", "dev_wml"]
    rows = []
    for name in order:
        x = a.loc[name]
        rows.append(" & ".join([DISPLAY[name], _num(100 * x.alpha_ann, 1, sign=True),
                                _num(x.t_alpha, 1)]
                               + [_num(x[f"b_{c}"]) + ("$^{*}$" if abs(x[f"t_{c}"]) > 1.96 else "")
                                  for c in cols] + [_num(x.r2)]))
    head = ("Contestant & $\\alpha$ & $t$ & Mkt & SMB & HML & RMW & CMA & WML & $R^2$")
    return _tabular("lrrrrrrrrr", head, rows)


def tex_warmup(runs: dict, races: dict, sub: pd.DataFrame, powers: dict, order: list[str]) -> str:
    ws = sorted(runs, reverse=True)                                       # 120, 80, 60
    g = sub[sub.warmup == min(ws)].set_index("portfolio")["gfc_return"]
    rows = []
    for name in order:
        cells = [DISPLAY[name]]
        for w in ws:
            t = races[w].set_index("portfolio")
            cells += [_num(t.loc[name, "sharpe"]), _p(t.loc[name].get("p_boot", np.nan))]
        cells.append(f"${100 * g[name]:.0f}$\\%")
        rows.append(" & ".join(cells))
    foot = [" & ".join(["Out-of-sample window"] + [
        f"\\multicolumn{{2}}{{r}}{{{runs[w].index[0]:%Y-%m}--{runs[w].index[-1]:%Y-%m}}}"
        for w in ws] + [""]),
        " & ".join(["Months"] + [f"\\multicolumn{{2}}{{r}}{{{len(runs[w])}}}" for w in ws] + [""]),
        " & ".join(["Power, min-variance vs 1/N"] + [
            f"\\multicolumn{{2}}{{r}}{{{100 * powers[w]['power_at_observed']:.0f}\\%}}"
            for w in ws] + [""]),
        " & ".join(["MDES (annualized Sharpe)"] + [
            f"\\multicolumn{{2}}{{r}}{{{powers[w]['mdes_ann']:.2f}}}" for w in ws] + [""])]
    head = ("& \\multicolumn{2}{c}{Warmup " + "} & \\multicolumn{2}{c}{Warmup ".join(
        str(w) for w in ws) + "} & GFC \\\\\n"
        + " ".join(f"\\cmidrule(lr){{{2 + 2 * k}-{3 + 2 * k}}}" for k in range(len(ws)))
        + "\nContestant" + " & Sharpe & $p$" * len(ws) + " & return")
    return _tabular("l" + "rr" * len(ws) + "r", head, rows, foot)


def tex_active(it: pd.DataFrame, order: list[str]) -> str:
    t = it.set_index("portfolio")
    rows = []
    for name in order:
        x = t.loc[name]
        if name == "1/N":
            cells = ["---"] * 4 + [_num(x["appraisal_CAPM"]), _num(x["appraisal_Carhart 4F"])] + ["---"] * 4
        else:
            cells = [_pct(x.active_ann), _pct(x.te_ann), _num(x.ir), _p(x.p_ir),
                     _num(x["appraisal_CAPM"]), _num(x["appraisal_Carhart 4F"]),
                     _num(x["appraisal_vs_1N_4FEM"]),
                     f"{100 * x.ahead_36m:.0f}\\%", f"{100 * x.ahead_60m:.0f}\\%",
                     f"{100 * x.ahead_120m:.0f}\\%"]
        rows.append(" & ".join([DISPLAY[name]] + cells))
    head = ("& \\multicolumn{4}{c}{Against 1/N} & \\multicolumn{3}{c}{Appraisal ratio} & "
            "\\multicolumn{3}{c}{Ahead of 1/N} \\\\\n"
            "\\cmidrule(lr){2-5} \\cmidrule(lr){6-8} \\cmidrule(lr){9-11}\n"
            "Contestant & Active & TE & IR & $p$ & CAPM & 4F & vs 1/N & 3y & 5y & 10y")
    return _tabular("l" + "r" * 10, head, rows)


